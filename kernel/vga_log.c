void draw_glyph(int x, int y, char c, uint32_t color) {
    if (!primary_fb) return;
    uint8_t *fb = (uint8_t*)primary_fb->address;
    const uint8_t *glyph = font8x8[(uint8_t)c];
    for (int gy = 0; gy < 8; gy++) {
        if (y + gy >= (int)primary_fb->height) break;
        for (int gx = 0; gx < 8; gx++) {
            if (x + gx >= (int)primary_fb->width) break;
            if (glyph[gy] & (0x80 >> gx)) {
                uint32_t *pixel = (uint32_t*)(fb + (y + gy) * primary_fb->pitch + (x + gx) * 4);
                *pixel = color;
            }
        }
    }
}

void vga_log(const char* str) {
    if (!vga_enabled || !primary_fb) return;
    uint8_t *fb = (uint8_t*)primary_fb->address;
    while (*str) {
        if (*str == '\n') {
            term_x = 0; term_y += 10;
        } else if (*str == '\r') {
            term_x = 0;
        } else {
            draw_glyph(term_x, term_y, *str, 0xFFFFFFFF);
            term_x += 8;
            if (term_x >= (int)primary_fb->width - 8) {
                term_x = 0; term_y += 10;
            }
        }
        if (term_y >= (int)primary_fb->height - 10) {
            memset(fb, 0, primary_fb->height * primary_fb->pitch);
            term_x = 0; term_y = 0;
        }
        str++;
    }
}
