void kpanic(const char* m) {
    struct panic_framebuffer* fb = get_kernel_framebuffer();
    if (fb) panic_printf(fb, "PANIC: %s\n", (uintptr_t)m, 0);
    while(1) __asm__("cli; hlt");
}
